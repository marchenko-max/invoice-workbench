// Screenshots of the main screens for a visual check: node test/shots.js  -> test/out/shot-*.png
'use strict';
const path = require('node:path');
const fs = require('node:fs');
const { launch } = require('./cdp.js');
const ROOT = path.resolve(__dirname, '..');
require('node:child_process').execFileSync(process.execPath, [path.join(ROOT, 'tools', 'build.js')]);
const URL = 'file://' + path.join(ROOT, 'dist', 'index.html');
const OUT = path.join(__dirname, 'out');
(async () => {
  const profile = path.join(__dirname, '.chrome-shots');
  fs.rmSync(profile, { recursive: true, force: true });
  const b = await launch({ width: 1360, height: 900, profile });
  const shot = (name) => b.screenshot(path.join(OUT, 'shot-' + name + '.png'));
  await b.goto(URL, 2400);
  await shot('example-light');
  await b.eval('window.scrollTo(0, 520)'); await b.wait(300);
  await shot('example-light-scrolled');
  await b.eval('window.scrollTo(0, 0)');
  await b.clickText('button', 'Add my company');
  await b.waitFor('document.querySelector("#dialog").open');
  await b.fill('#co-name', 'Zkušební s.r.o.'); await b.fill('#co-ico', '27082440'); await b.fill('#co-dic', 'CZ27082440');
  await b.fill('#co-street', 'Dlouhá 1'); await b.fill('#co-zip', '110 00'); await b.fill('#co-city', 'Praha');
  await b.check('#co-vat', true); await b.fill('#co-account', '19-2000145399/0800');
  await b.wait(500);
  await shot('dialog-light');
  await b.clickText('#dialog button', 'Save');
  await b.waitFor('!document.querySelector("#dialog").open'); await b.wait(500);
  await b.fill('#to-name', 'Odběratel a.s.'); await b.fill('#to-ico', '27082440');
  const id = await b.eval('document.querySelector(".item").id');
  await b.fill('#' + id + '-desc', 'Práce na projektu'); await b.fill('#' + id + '-qty', '3'); await b.fill('#' + id + '-price', '1210');
  await b.fill('#f-status', 'issued'); await b.wait(1600);
  await b.eval('location.hash = "#documents"'); await b.wait(400);
  await b.clickText('button', 'New document'); await b.wait(300);
  await b.fill('#to-name', 'Druhý zákazník s.r.o.'); await b.wait(1500);
  await b.eval('location.hash = "#documents"'); await b.wait(500);
  await shot('documents-light');
  await b.eval('location.hash = "#companies"'); await b.wait(500);
  await shot('companies-light');
  await b.setDark(true);
  await b.eval('location.hash = "#documents"'); await b.wait(500);
  await shot('documents-dark');
  await b.eval('document.querySelector(".ledger tbody tr").click()'); await b.wait(700);
  await shot('editor-dark');
  await b.eval('window.scrollTo(0, 700)'); await b.wait(300);
  await shot('editor-dark-scrolled');
  await b.eval('location.hash = "#backup"'); await b.wait(500);
  await shot('backup-dark');
  await b.setDark(false);
  await b.setViewport(390, 800, true);
  await b.eval('location.hash = "#documents"'); await b.wait(500);
  await shot('phone-documents');
  await b.eval('document.querySelector(".ledger tbody tr").click()'); await b.wait(700);
  await shot('phone-editor');
  await b.eval('window.scrollTo(0, 900)'); await b.wait(300);
  await shot('phone-editor-scrolled');
  console.log('errors', JSON.stringify(b.errors));
  await b.close();
  fs.rmSync(profile, { recursive: true, force: true });
})();
